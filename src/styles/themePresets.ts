export function getThemePreset(theme: ThemeKey): ThemePreset {
  return themePresets[theme] ?? themePresets.cinematic;
}

export function getMotionDuration(preset: MotionPreset): number {
  return MOTION_DURATIONS[preset] ?? 600;
}

export function getMotionEasing(preset: MotionPreset): string {
  switch (preset) {
    case 'cinematic':
      return 'cubic-bezier(0.16, 1, 0.3, 1)';
    case 'playful':
      return 'cubic-bezier(0.34, 1.56, 0.64, 1)';
    case 'fast':
      return 'cubic-bezier(0.4, 0, 0.2, 1)';
    case 'editorial':
      return 'cubic-bezier(0.25, 0.46, 0.45, 0.94)';
    case 'soft':
    default:
      return 'cubic-bezier(0.22, 1, 0.36, 1)';
  }
}
